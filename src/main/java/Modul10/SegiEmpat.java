public class SegiEmpat { //Awal dari class SegiEmpat
    public static void main(String[] args) {
        int panjang, lebar;
        /*ini untuk deklarasi variabel bilangan bulat
         *dari panjang dan lebar
         */
        double luas;
        /*ini untuk deklarasi variabel bilangan koma 
         *atau desimal dari luas
         */
        
        panjang = 4;
        //ini adalah inisialisasi nilai variabel panjang
        lebar = 5;
        //ini adalah inisialisasi nilai variabel lebar
        luas = panjang * lebar;
        /*ini adalah rumus untuk mencari luas segi empat
         *yang dimana variabel panjang di kali dengan lebar,
         *kemudian akan disimpan kembali di variabel luas
         */
        System.out.print("Hasil dari luas segi empat adalah : "+luas);
        /*Perintah ini untuk menampilkan hasil dari luas segiempat
         *dan memanggil variabel luas
         */
    }
} //Akhir dari class SegiEmpat
